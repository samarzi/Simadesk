/** Renders a ? button that uses the same metric-tip-btn class as Analytics. */
export function helpBtn(moduleKey: string): string {
  return `<button type="button" class="metric-tip-btn" style="width:20px;height:20px;font-size:11px;margin-left:0"
    onclick="window.__showHelp?.('${moduleKey}')" title="Справка по разделу" aria-label="Справка">?</button>`;
}

export function initHelpModal(): void {
  if (document.getElementById('help-module-host')) return;

  const host = document.createElement('div');
  host.id = 'help-module-host';
  host.className = 'metric-tip-host';
  host.style.display = 'none';
  host.innerHTML = `
    <div class="metric-tip-backdrop" data-help-close="1"></div>
    <div class="metric-tip-modal" role="dialog" aria-modal="true" style="max-width:500px">
      <button type="button" class="metric-tip-close" data-help-close="1" aria-label="Закрыть">✕</button>
      <div id="help-module-body" class="metric-tip-body"></div>
    </div>
  `;
  document.body.appendChild(host);

  host.addEventListener('click', (e) => {
    if ((e.target as HTMLElement).dataset.helpClose === '1') host.style.display = 'none';
  });
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && host.style.display !== 'none') host.style.display = 'none';
  });

  (window as any).__showHelp = (key: string) => {
    const c = HELP[key]; if (!c) return;
    const body = document.getElementById('help-module-body')!;
    body.innerHTML = `
      <div class="metric-tip-head">
        <div class="metric-tip-title">${c.icon} ${c.title}</div>
        <span class="metric-tip-badge" style="background:#005bff22;color:#005bff;border-color:#005bff55">Справка</span>
      </div>
      ${c.sections.map(s => `
        <div class="metric-tip-section">
          <div class="metric-tip-section-title">${s.h}</div>
          <div class="metric-tip-text">${s.t}</div>
        </div>
      `).join('')}
    `;
    host.style.display = 'flex';
  };
}
