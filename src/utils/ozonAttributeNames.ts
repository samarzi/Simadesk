/**
 * Get a human-readable attribute name.
 * Priority: API-provided name → built-in dictionary → "Атрибут {id}"
 */
export function getAttrName(attrId: number, apiName?: string | null): string {
  if (apiName && apiName.trim() && !apiName.startsWith('Атрибут')) {
    return apiName.trim();
  }
  return OZON_ATTR_NAMES[attrId] ?? `Атрибут ${attrId}`;
}

/**
 * Merge API-provided attribute names into the built-in dictionary.
 * Call this after fetching /v1/description-category/attribute.
 */
export function mergeAttrNames(apiMap: Map<number, string>): void {
  for (const [id, name] of apiMap) {
    if (name && name.trim()) {
      OZON_ATTR_NAMES[id] = name.trim();
    }
  }
}
