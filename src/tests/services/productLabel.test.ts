import { describe, it, expect } from 'vitest';
import { productLabel, plural } from '@/services/aiPageCapabilities';

describe('productLabel — подпись товара в задачах', () => {
  it('артикул идёт первым, название следом', () => {
    // По названию товар не найти ни в кабинете МП, ни у поставщика — ищут по артикулу
    expect(productLabel('BC-4471', 'Кроссовки мужские Bocosa'))
      .toBe('[BC-4471] Кроссовки мужские Bocosa');
  });

  it('артикул не обрезается, даже если название длинное', () => {
    const long = 'Кроссовки мужские Bocosa из натуральной кожи на толстой подошве, чёрные';
    const out = productLabel('BC-4471', long);
    expect(out.startsWith('[BC-4471] ')).toBe(true);
  });

  it('слишком длинное название укорачивается многоточием', () => {
    const long = 'Кроссовки мужские Bocosa из натуральной кожи на толстой подошве, чёрные, размер 43';
    const out = productLabel('BC-4471', long, 30);
    expect(out).toMatch(/…$/);
    expect(out.length).toBeLessThan(long.length);
  });

  it('без названия остаётся один артикул', () => {
    expect(productLabel('BC-4471', '')).toBe('[BC-4471]');
    expect(productLabel('BC-4471', null)).toBe('[BC-4471]');
  });

  it('без артикула остаётся название — задача всё равно осмысленна', () => {
    expect(productLabel('', 'Кроссовки')).toBe('Кроссовки');
    expect(productLabel(undefined, 'Кроссовки')).toBe('Кроссовки');
  });

  it('прочерк вместо артикула не превращается в пустые скобки', () => {
    expect(productLabel('—', 'Кроссовки')).toBe('Кроссовки');
  });

  it('когда нет ничего — возвращает прочерк, а не пустую строку', () => {
    expect(productLabel('', '')).toBe('—');
    expect(productLabel(null, undefined)).toBe('—');
  });

  it('числовой артикул (nm_id) обрабатывается наравне со строковым', () => {
    expect(productLabel(123456789, 'Кроссовки')).toBe('[123456789] Кроссовки');
  });

  it('пробелы по краям не попадают в подпись', () => {
    expect(productLabel('  BC-4471  ', '  Кроссовки  ')).toBe('[BC-4471] Кроссовки');
  });
});

describe('plural — склонение после числа', () => {
  it('единственное число', () => {
    expect(plural(1, 'позиция', 'позиции', 'позиций')).toBe('1 позиция');
    expect(plural(21, 'позиция', 'позиции', 'позиций')).toBe('21 позиция');
  });

  it('от двух до четырёх', () => {
    expect(plural(2, 'позиция', 'позиции', 'позиций')).toBe('2 позиции');
    expect(plural(23, 'позиция', 'позиции', 'позиций')).toBe('23 позиции');
  });

  it('множественное число', () => {
    expect(plural(5, 'позиция', 'позиции', 'позиций')).toBe('5 позиций');
    expect(plural(816, 'позиция', 'позиции', 'позиций')).toBe('816 позиций');
    expect(plural(0, 'позиция', 'позиции', 'позиций')).toBe('0 позиций');
  });

  it('подростковые числа — исключение из правила', () => {
    // 11–14 всегда «позиций», хотя последняя цифра говорит об обратном
    expect(plural(11, 'позиция', 'позиции', 'позиций')).toBe('11 позиций');
    expect(plural(12, 'позиция', 'позиции', 'позиций')).toBe('12 позиций');
    expect(plural(14, 'позиция', 'позиции', 'позиций')).toBe('14 позиций');
    expect(plural(111, 'позиция', 'позиции', 'позиций')).toBe('111 позиций');
  });
});
